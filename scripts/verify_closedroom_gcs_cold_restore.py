#!/usr/bin/env python3
"""Opt-in genuine encrypted GCS cold snapshot restore verification on the Mac.

Run ONLY inside the approved user login-session broker. Reads the existing
0600 receipt + encrypted recovery envelope + one-time recovery code from
native Keychain. Restores to a freshly created throwaway directory in the
user's home; never touches existing ClosedRoom recording/transcript/catalog
roots. Does NOT imply recovery key was exported independently of this Mac.

Output contains only non-secret aggregate counts; no paths or credentials.
"""
from __future__ import annotations

from contextlib import closing
import json
import os
from pathlib import Path
import re
import sqlite3
import sys
import tempfile
from urllib.parse import quote

from local_asr_server.storage.cold_migration import (
    MigrationBlocked, restore_snapshot, _private_json,
)
from local_asr_server.storage.gcs_oauth import OAuthUnavailable
from local_asr_server.storage.key_recovery import (
    ArchiveKeyUnavailable, RecoveryFailed, recover_key, native_macos_keychain,
)

RECOVERY_SERVICE = "com.closedroom.app.gcs.migration.recovery"
RECOVERY_ACCOUNT = "cold-migration-v1"
HOME_CONFIG = Path.home() / ".config/closedroom"
CLIENT_JSON = HOME_CONFIG / "oauth-desktop.json"
RECEIPT = HOME_CONFIG / "cold-migration-receipt.json"
ENVELOPE = HOME_CONFIG / "cold-migration-recovery.json"
CODE_PATTERN = re.compile(r"CR1-[A-Za-z0-9_-]{43}\Z")


class EphemeralRecoveryVault:
    """Derive the archive key from *portable* recovery materials, never the
    macOS archive-key Keychain entry. An independent Mac still needs its own
    copy of both recovery materials and the code.
    """
    def import_recovery(self, envelope: dict, code: str) -> bytes:
        return recover_key(envelope, code)


def _read_code() -> str:
    try:
        code = native_macos_keychain().get_password(RECOVERY_SERVICE, RECOVERY_ACCOUNT)
    except Exception:
        raise MigrationBlocked("RECOVERY_CODE_KEYCHAIN_UNAVAILABLE") from None
    if not isinstance(code, str) or CODE_PATTERN.fullmatch(code) is None:
        raise MigrationBlocked("RECOVERY_CODE_NOT_AVAILABLE")
    return code


def verify_isolated_restore() -> dict[str, object]:
    if sys.platform != "darwin" or os.environ.get("CLOSEDROOM_TRUSTED_LOGIN_BROKER") != "1":
        raise MigrationBlocked("TRUSTED_LOGIN_BROKER_REQUIRED")
    if os.environ.get("GITHUB_ACTIONS") == "true":
        raise MigrationBlocked("RESTORE_MUST_NOT_READ_KEYCHAIN_IN_CI")
    if HOME_CONFIG.is_symlink() or not HOME_CONFIG.is_dir():
        raise MigrationBlocked("PRIVATE_CONFIG_DIRECTORY_REQUIRED")

    # Check the private receipt before any download to prevent a run against
    # a foreign bucket, malformed manifest or mismatched object.
    receipt = _private_json(RECEIPT)
    if receipt.get("format") != "closedroom-cold-snapshot-v1":
        raise MigrationBlocked("RESTORE_RECEIPT_UNSUPPORTED")
    asset = receipt.get("asset")
    summary = receipt.get("summary")
    if not isinstance(asset, dict) or not isinstance(summary, dict):
        raise MigrationBlocked("RESTORE_RECEIPT_INVALID")
    if asset.get("bucket") != "project-tests-498508-closedroom-test":
        raise MigrationBlocked("RESTORE_BUCKET_MISMATCH")
    if (type(summary.get("file_count")) is not int or summary["file_count"] < 1):
        raise MigrationBlocked("RESTORE_RECEIPT_INVALID")

    code = _read_code()
    # A TemporaryDirectory creates its private own 0700 directory in user
    # home; restore_snapshot writes only below it and does not activate the
    # recovered dataset in ClosedRoom. Its lifecycle removes only scratch
    # generated by THIS verification (even on an ordinary failure).
    with tempfile.TemporaryDirectory(prefix=".closedroom-restore-proof-", dir=Path.home()) as temp:
        work = Path(temp)
        target = work / "dataset"
        result = restore_snapshot(
            client_json=CLIENT_JSON,
            receipt=RECEIPT,
            recovery_file=ENVELOPE,
            recovery_code=code,
            target=target,
            work_dir=work,
            vault=EphemeralRecoveryVault(),
        )
        if (result.get("status") != "cold_snapshot_restored_to_isolated_directory"
                or result.get("restored_files") != summary["file_count"]):
            raise MigrationBlocked("RESTORE_FILE_COUNT_MISMATCH")
        db_path = target / "catalog/closedroom.db"
        if not db_path.is_file() or db_path.is_symlink():
            raise MigrationBlocked("RESTORE_CATALOG_MISSING")
        db_uri = "file:" + quote(str(db_path.absolute()), safe="/") + "?mode=ro&immutable=1"
        try:
            with closing(sqlite3.connect(db_uri, uri=True, timeout=5)) as db:
                if db.execute("PRAGMA quick_check(1)").fetchone() != ("ok",):
                    raise MigrationBlocked("RESTORE_CATALOG_INTEGRITY_FAILED")
                recordings = db.execute("SELECT COUNT(*) FROM recordings").fetchone()[0]
                transcriptions = db.execute("SELECT COUNT(*) FROM transcriptions").fetchone()[0]
                if recordings < 1 or transcriptions < 1:
                    raise MigrationBlocked("RESTORE_CATALOG_INCOMPLETE")
        except sqlite3.Error:
            raise MigrationBlocked("RESTORE_CATALOG_INVALID") from None
        return {
            "status": "cold_snapshot_restored_verified_isolated",
            "restored_files": result["restored_files"],
            "recordings_rows": recordings,
            "transcriptions_rows": transcriptions,
            "authenticated_decryption": True,
            "used_portable_recovery_material": True,
            "verified_on_second_mac": False,
            "independent_code_custody_verified": False,
            "originals_deleted": False,
            "active_app_data_modified": False,
        }


def main() -> int:
    try:
        print(json.dumps(verify_isolated_restore(), sort_keys=True))
        return 0
    except MigrationBlocked as exc:
        code = str(exc)
    except OAuthUnavailable as exc:
        code = exc.code
    except (ArchiveKeyUnavailable, RecoveryFailed):
        code = "KEYCHAIN_OR_RECOVERY_FAILED"
    except Exception:
        code = "ISOLATED_RESTORE_FAILED"
    if not re.fullmatch(r"[A-Z0-9_]{3,80}", code):
        code = "ISOLATED_RESTORE_FAILED"
    print(json.dumps({"status": "blocked", "error_code": code}, sort_keys=True),
          file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
